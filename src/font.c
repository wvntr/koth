/* ---- mapeamento codepoint -> indice na fonte 8x8 ----
   Para acentos latinos usamos o glifo base sem acento (aproximacao legivel). */
static int glyph_index(uint32_t cp){
    if(cp>=0x20&&cp<=0x7E) return cp-0x20;
    switch(cp){
    case 0xA0: return ' '-0x20;                       /* nbsp */
    case 0xAB: return '<'-0x20; case 0xBB: return '>'-0x20;   /* guillemets */
    case 0x2018: case 0x2019: case 0x201B: return '\''-0x20; /* quotes */
    case 0x201C: case 0x201D: case 0x201F: return '"'-0x20;
    case 0x2013: case 0x2014: case 0x2010: case 0x2011: return '-'-0x20; /* dashes */
    case 0x2022: return '*'-0x20;                     /* bullet */
    case 0x2026: return '.'-0x20;                     /* ellipsis -> ... desenha 1 ponto; aceitavel */
    case 0x2192: return '>'-0x20; case 0x2190: return '<'-0x20;
    case 0x00A9: return 'c'-0x20; case 0x00AE: return 'r'-0x20;
    case 0x2122: return 'T'-0x20;
        }
    /* acentos: strip para letra base */
    static const struct { uint32_t cp; char base; } acc[]={
      {0xC0,'A'},{0xC1,'A'},{0xC2,'A'},{0xC3,'A'},{0xC4,'A'},{0xC5,'A'},{0xC6,'A'},
      {0xC7,'C'},{0xC8,'E'},{0xC9,'E'},{0xCA,'E'},{0xCB,'E'},{0xCC,'I'},{0xCD,'I'},
      {0xCE,'I'},{0xCF,'I'},{0xD0,'D'},{0xD1,'N'},{0xD2,'O'},{0xD3,'O'},{0xD4,'O'},
      {0xD5,'O'},{0xD6,'O'},{0xD8,'O'},{0xD9,'U'},{0xDA,'U'},{0xDB,'U'},{0xDC,'U'},
      {0xDD,'Y'},{0xDE,'P'},{0xDF,'B'},
      {0xE0,'a'},{0xE1,'a'},{0xE2,'a'},{0xE3,'a'},{0xE4,'a'},{0xE5,'a'},{0xE6,'a'},
      {0xE7,'c'},{0xE8,'e'},{0xE9,'e'},{0xEA,'e'},{0xEB,'e'},{0xEC,'i'},{0xED,'i'},
      {0xEE,'i'},{0xEF,'i'},{0xF0,'d'},{0xF1,'n'},{0xF2,'o'},{0xF3,'o'},{0xF4,'o'},
      {0xF5,'o'},{0xF6,'o'},{0xF8,'o'},{0xF9,'u'},{0xFA,'u'},{0xFB,'u'},{0xFC,'u'},
      {0xFD,'y'},{0xFE,'p'},{0xFF,'y'},
      {0x100,'A'},{0x101,'a'},{0x102,'A'},{0x103,'a'},{0x104,'A'},{0x105,'a'},
      {0x106,'C'},{0x107,'c'},{0x108,'C'},{0x109,'c'},{0x10A,'C'},{0x10B,'c'},{0x10C,'C'},{0x10D,'c'},
      {0x10E,'D'},{0x10F,'d'},{0x110,'D'},{0x111,'d'},{0x112,'E'},{0x113,'e'},{0x114,'E'},{0x115,'e'},
      {0x116,'E'},{0x117,'e'},{0x118,'E'},{0x119,'e'},{0x11A,'E'},{0x11B,'e'},{0x11C,'G'},{0x11D,'g'},
      {0x15E,'S'},{0x15F,'s'},{0x162,'T'},{0x163,'t'},{0x164,'T'},{0x165,'t'},
      {0x16E,'U'},{0x16F,'u'},{0x172,'U'},{0x173,'u'},{0x174,'U'},{0x175,'u'},
      {0x176,'U'},{0x177,'u'},{0x178,'Y'},{0x179,'Z'},{0x17A,'z'},{0x17B,'Z'},{0x17C,'z'},{0x17D,'Z'},{0x17E,'z'},
      {0x192,'f'},{0x1FA,'A'},{0x1FB,'a'},{0x1FC,'E'},{0x1FD,'e'},{0x1FE,'O'},{0x1FF,'o'},
      {0x219,'H'},{0x21A,'h'},{0x21B,'t'},
    };
    for(unsigned i=0;i<sizeof(acc)/sizeof(acc[0]);i++)
        if(acc[i].cp==cp) return acc[i].base-0x20;
    if(cp>=0x2500&&cp<=0x257F) return '_'-0x20; /* linhas -> traco */
    return '?'-0x20;
}

const uint8_t *glyph_for_cp(uint32_t cp){
    int idx=glyph_index(cp);
    if(idx<0||idx>95) idx='?'-0x20;
    return FONT8X8[idx];
}

int text_width_utf8(const char *s, int scale){
    const int sp = GLYPH_W*scale;
    int w=0;
    uint32_t n=strlen(s),i=0;
    while(i<n){
        uint32_t cp=utf8_next(s,n,&i);
        if(!cp)break;
        if(cp==0xA0) cp=' ';
        if(cp>=0x20&&cp<=0x7E) w+=sp;
        else if(cp==0x398||cp==0x131) w+=sp; /* fallback */
        else w+=sp; /* desconhecido desenha caixa/espaco com mesma metrica */
    }
    return w;
}
